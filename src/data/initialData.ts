export function computeMomentumScore(upvotes: number, comments: number, hoursElapsed: number): number {
  const safeHours = Math.max(hoursElapsed, 0.1);
  const score = (upvotes + comments * 1.5) / Math.pow(safeHours, 1.2);
  return Number(score.toFixed(2));
}

